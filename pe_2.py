NON_DEAL_KEYWORDS = ["appoints", "named partner", "promotes", "promoted", "welcomes", "award", "strengthens origination"]
DEAL_KEYWORDS = ["investment in", "acquires", "acquire", "acquisition", "sale of", "sells", "merger", "partners with"]

def parse_record(item):
    text_corpus = (item["headline"] + " " + item["body"]).lower()
    headline = item["headline"]

    # 1. Distinguish Real Deals from Personnel / Corporate PR
    is_deal = any(k in text_corpus for k in DEAL_KEYWORDS) and not any(k in headline.lower() for k in NON_DEAL_KEYWORDS)

    if not is_deal:
        return {
            "source_pe_firm": "Norwest Equity Partners",
            "headline": headline,
            "url": item["url"],
            "announcement_date": item["date_str"],
            "is_verified_deal": False,
            "transaction_type": "Personnel / Non-Deal",
            "buyer_entity": None,
            "target_company": None,
            "target_industry": None,
            "strategic_rationale": None,
            "deal_value_disclosed": False,
            "evidence_snippet": "Classified as internal executive / origination update."
        }

    # 2. Transaction Classification
    if any(k in text_corpus for k in ["sale of", "sells to"]):
        tx_type = "Full Exit / Sale"
    elif any(k in text_corpus for k in ["acquire", "merger"]):
        tx_type = "Add-On Acquisition"
    else:
        tx_type = "Platform Investment"

    # 3. Target Industry Classification
    if any(k in text_corpus for k in ["produce", "food", "canopy", "textiles", "wallcoverings"]):
        industry = "Consumer Products & Distribution"
    elif any(k in text_corpus for k in ["tech", "software", "infrastructure", "it solutions"]):
        industry = "Business & IT Services"
    else:
        industry = "General Middle Market"

    # 4. Strategic Rationale
    if any(k in text_corpus for k in ["geographic footprint", "expansion", "reach"]):
        rationale = "Geographic Expansion"
    elif any(k in text_corpus for k in ["patents", "category leader", "specialty offerings", "manufacturing"]):
        rationale = "Product Line & Capability Extension"
    else:
        rationale = "Undisclosed / Core Growth"

    # 5. Distinguish Buyer vs Target
    buyer = "Norwest Equity Partners"
    target = "Unknown"

    if "Sale of" in headline and "to" in headline:
        parts = headline.split("Sale of")[1].split("to")
        target = parts[0].strip()
        buyer = parts[1].strip()
    elif "Investment in" in headline:
        target = headline.split("Investment in")[1].split(",")[0].strip()
    elif "Acquire" in headline:
        parts = re.split(r"Acquire|Acquires", headline)
        buyer = parts[0].replace("Announces Agreement to", "").strip()
        target = parts[1].strip()

    # 6. Check for Disclosed Valuation (Missing != 0)
    has_price = bool(re.search(r"\$\d+(\.\d+)?\s*(million|billion|m|b)", text_corpus))

    return {
        "source_pe_firm": "Norwest Equity Partners",
        "headline": headline,
        "url": item["url"],
        "announcement_date": item["date_str"],
        "is_verified_deal": True,
        "transaction_type": tx_type,
        "buyer_entity": buyer,
        "target_company": target,
        "target_industry": industry,
        "strategic_rationale": rationale,
        "deal_value_disclosed": has_price,
        "evidence_snippet": item["body"][:130] + "..."
    }

